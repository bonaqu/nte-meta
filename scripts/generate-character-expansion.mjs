for (const c of characters) {
  const team = teams[c.slug];
  const guideId = `guide-${c.slug}-0031`;
  const teamId = `team-${c.slug}-0031`;
  const memberSlugs = team.members.map(([slug]) => sql(slug)).join(', ');
  const synergy = `${c.teams}\n\nИсточник состава: ${team.source}\nСверено ${checkedAt}. Пробуждения, дуги и условия боя влияют на результат${c.slug === 'akane' ? '; стартовая рекомендация для нового персонажа' : ''}.`;
  lines.push(`INSERT OR IGNORE INTO teams (id, slug, guide_id, title, team_type, budget, difficulty, power, good_at, weak_at, synergy, rotation, rotation_steps_json, status)
SELECT ${[teamId, teamId, guideId, team.title, c.slug === 'zankou' ? 'Горение' : 'Рекомендация источника', 'Mixed', 'Базовый цикл персонажа; тайминг уточняется под состав'].map(sql).join(', ')}, 0, '', '', ${[synergy, c.rotation.join('\n'), JSON.stringify(c.rotation), 'published'].map(sql).join(', ')} WHERE EXISTS (SELECT 1 FROM expansion_guides_0031 WHERE id = ${sql(guideId)}) AND (SELECT COUNT(*) FROM characters WHERE slug IN (${memberSlugs})) = 4;`);
  lines.push(`INSERT OR IGNORE INTO team_members (team_id, character_id, role, position)
${team.members.map(([slug, role], index) => `SELECT ${sql(teamId)}, id, ${sql(role)}, ${index + 1} FROM characters WHERE slug = ${sql(slug)} AND EXISTS (SELECT 1 FROM expansion_guides_0031 WHERE id = ${sql(guideId)}) AND EXISTS (SELECT 1 FROM teams WHERE id = ${sql(teamId)} AND guide_id = ${sql(guideId)})`).join('\nUNION ALL\n')};`);
}
lines.push('DROP TABLE expansion_guides_0031;');
// This dated source uses the site's native S/A/B/C/D scale. Never convert Kaiden T0 to S silently.
const ranks = {
  S: [
    'nanally',
    'lacrimosa',
    'chaos',
    'shinku',
    'zankou',
    'blackbird',
    'daffodill',
    'esper-zero',
    'hotori',
    'linko',
    'iroi',
    'sakiri',
  ],
  A: ['baicang', 'chiz', 'hathor', 'jiuyuan', 'haniel'],
  B: ['aurelia', 'fadia', 'adler'],
  C: ['mint', 'skia'],
  D: ['edgar'],
};
const aRanks = new Set(['aurelia', 'haniel', 'adler', 'mint', 'skia', 'edgar']);
for (const [tier, slugs] of Object.entries(ranks))
  for (const slug of slugs) {
    const note = `Ориентир Icy Veins, 28.09.2026; сверено ${checkedAt}. ${aRanks.has(slug) ? 'A6' : 'A0'}, оценка в боевой роли источника. https://www.icy-veins.com/neverness-to-everness/tier-list`;
    const old = prior.items.find(
      (x) =>
        x.characterId === slug ||
        (slug === 'shinku' &&
          x.characterId === 'ec50ff3d-4340-4dad-89b4-1e14b95d6c21'),
    );
    if (old)
      lines.push(
        `UPDATE tierlist_items SET tier = ${sql(tier)}, note = ${sql(note)} WHERE tierlist_id = ${sql(prior.id)} AND character_id = ${sql(old.characterId)} AND tier = ${sql(old.tier)} AND COALESCE(note, '') = ${sql(old.note)};`,
      );
    lines.push(`INSERT OR IGNORE INTO tierlist_items (tierlist_id, character_id, tier, tier_rank, position, note)
SELECT tierlists.id, characters.id, ${sql(tier)}, 30, 100, ${sql(note)} FROM tierlists JOIN characters ON characters.slug = ${sql(slug)} WHERE tierlists.id = ${sql(prior.id)} AND tierlists.status = 'published';`);
  }
const changelog = [
  '21.10.2026: каталог расширен до 24 персонажей. Аканэ Рин пока без оценки.',
  'Ориентир: Icy Veins, 28.09.2026, https://www.icy-veins.com/neverness-to-everness/tier-list . S-ранговые персонажи оценены при A0, A-ранговые при A6; роли и условия различаются.',
  'Изменённые редактором позиции сохранены. Внешняя шкала Kaiden T0/T1 не переводится автоматически в S/A.',
  ...prior.changelog,
];
lines.push(
  `UPDATE tierlists SET patch_version = '1.4', changelog_json = ${sql(JSON.stringify(changelog))}, updated_at = CURRENT_TIMESTAMP WHERE id = ${sql(prior.id)} AND patch_version = ${sql(prior.patch)} AND changelog_json = ${sql(JSON.stringify(prior.changelog))};`,
);
await writeFile(
  new URL('../migrations/0031_expand_character_catalog.sql', import.meta.url),
  lines.join('\n\n') + '\n',
);
