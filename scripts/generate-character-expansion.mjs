import { readFile, writeFile } from 'node:fs/promises';

// Reviewed editorial input, never generated from a live page during deployment.
const { characters, checkedAt } = JSON.parse(
  await readFile(
    new URL('./content/characters-1.4.json', import.meta.url),
    'utf8',
  ),
);
const prior = JSON.parse(
  (
    await readFile(
      new URL('../tests/fixtures/tierlist-public-before.json', import.meta.url),
      'utf8',
    )
  ).replace(/^\uFEFF/, ''),
);
const imageSources = JSON.parse(
  await readFile(
    new URL(
      '../public/assets/characters/NEW_CHARACTER_SOURCES.json',
      import.meta.url,
    ),
    'utf8',
  ),
);
const sql = (value) => `'${String(value ?? '').replaceAll("'", "''")}'`;
const lines = [
  '-- Reviewed catalogue expansion. No deletes or replacement of authored profiles/guides.',
  '-- Generated by scripts/generate-character-expansion.mjs; input reviewed on ' +
    checkedAt +
    '.',
  'CREATE TABLE expansion_guides_0031 (id TEXT PRIMARY KEY);',
];
for (const character of characters) {
  const c = character;
  // The previous frontend can load these during the API/Pages rollout. The new
  // frontend resolves the exact approved URLs to its bundled local copies.
  const image = imageSources.find(
    (source) => source.file === `public/assets/characters/${c.slug}.webp`,
  ).url;
  const splash =
    c.slug === 'akane'
      ? image
      : imageSources.find(
          (source) =>
            source.file === `public/assets/characters/splashes/${c.slug}.webp`,
        ).url;
  lines.push(`INSERT OR IGNORE INTO characters (id, slug, name, original_name, rarity, role, type, attribute, tier, premium_tier, image_url, splash_url, short_description, summary, tags_json, status, patch_version)
SELECT ${[c.slug, c.slug, c.name, c.originalName, 'S', c.role, c.role, c.attribute, 'A', 'A', image, splash, c.summary, c.summary, JSON.stringify([c.attribute, c.role]), 'published', c.releaseVersion].map(sql).join(', ')} WHERE NOT EXISTS (SELECT 1 FROM characters WHERE slug = ${sql(c.slug)});`);
  const biography =
    `${c.bio}\n\nСверено ${checkedAt}; краткий пересказ.\n\n` +
    c.sources.map((url) => `- [${new URL(url).hostname}](${url})`).join('\n');
  lines.push(`INSERT OR IGNORE INTO character_profiles (character_id, faction, arc_type, release_date, release_version, biography_short, biography_markdown, role_tags_json)
SELECT id, ${[c.faction, c.arcType, c.releaseDate, c.releaseVersion, c.bio, biography, JSON.stringify(c.role.split(' / '))].map(sql).join(', ')} FROM characters WHERE slug = ${sql(c.slug)};`);
  const guideId = `guide-${c.slug}-0031`;
  lines.push(
    `INSERT OR IGNORE INTO expansion_guides_0031 SELECT ${sql(guideId)} WHERE NOT EXISTS (SELECT 1 FROM guides JOIN characters ON characters.id = guides.character_id WHERE characters.slug = ${sql(c.slug)}) AND NOT EXISTS (SELECT 1 FROM guides WHERE id = ${sql(guideId)} OR slug = ${sql(`${c.slug}-build-guide`)});`,
  );
  lines.push(`INSERT OR IGNORE INTO guides (id, slug, character_id, title, summary, status, patch_version, author_name)
SELECT ${sql(guideId)}, ${sql(`${c.slug}-build-guide`)}, id, ${sql(`${c.name}: сборка, отряды и ротация`)}, ${sql(c.summary)}, 'published', '1.4', 'NTE Meta' FROM characters WHERE slug = ${sql(c.slug)} AND EXISTS (SELECT 1 FROM expansion_guides_0031 WHERE id = ${sql(guideId)});`);
  const sections = [
    ['Краткий вывод', 'overview', c.summary],
    ['Дуги, консоль и характеристики', 'builds', c.build],
    ['Приоритет навыков', 'skill-priority', c.skills],
    ['Отряды и замены', 'teams', c.teams],
    [
      'Базовая ротация',
      'rotations',
      c.rotation.map((step, i) => `${i + 1}. ${step}`).join('\n'),
    ],
    ['Условия и частые ошибки', 'tips', c.tips],
    [
      'Источники и актуальность',
      'sources',
      `Версия 1.4; источники открыты ${checkedAt}. Ротация — пересказ механик и рекомендаций, без замеров урона в игре. Пробуждения и наложения дуг меняют результат.\n\n` +
        c.sources
          .map(
            (url) =>
              `- [${new URL(url).hostname}${url.includes('kaiden') ? ': сборка и механики' : ''}](${url})`,
          )
          .join('\n'),
    ],
  ];
  for (const [index, [title, type, content]] of sections.entries())
    lines.push(`INSERT OR IGNORE INTO guide_sections (id, guide_id, title, section_type, content_markdown, position, meta_json)
SELECT ${[`${guideId}-${type}`, guideId, title, type, content].map(sql).join(', ')}, ${index + 1}, ${sql(JSON.stringify({ checkedAt, sourceUrls: c.sources, liveTested: false }))} WHERE EXISTS (SELECT 1 FROM expansion_guides_0031 WHERE id = ${sql(guideId)});`);
}
